"""Event-level evaluation manifest: the label format, and nothing else.

An evaluation set is a **manifest plus clips**.  The manifest is the only place
labels live, so the labels are reviewable, diff-able and hashable.

Ground truth is recorded at **event** level, not frame level: an accident is a
moment in a video, not a set of pixels.  Frame-level labels would tempt anyone
into splitting neighbouring frames across train/test, which leaks.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence, Tuple

__all__ = [
    "AnnotationQuality",
    "ClipLabel",
    "EvalManifest",
    "ManifestError",
    "load_manifest",
]

#: How trustworthy is this label?  This is a first-class field because a
#: metric computed over unverified labels is not a measurement of the system,
#: it is a measurement of whoever typed the labels.
GRADES = (
    "VERIFIED",      # human reviewed the event, confirmed it is what it claims
    "OPERATOR",      # a domain expert asserted it; not independently reviewed
    "PROVISIONAL",   # inferred, e.g. from the pipeline's own output - CIRCULAR
    "SYNTHETIC",     # generated by the project, never real footage
)


class ManifestError(ValueError):
    """The manifest is missing, malformed, or internally inconsistent."""


@dataclass
class EventLabel:
    """One labelled event inside a clip.

    ``start_seconds`` / ``end_seconds`` are on the **media** timeline (what the
    player shows), not wall clock.
    """

    kind: str                      # "accident" | "hard_negative" | "normal"
    start_seconds: float = 0.0
    end_seconds: float = 0.0
    subtype: str = ""              # e.g. "rear_end", "hard_brake", "occlusion"
    note: str = ""
    verified_by: str = ""

    @property
    def is_positive(self) -> bool:
        return self.kind == "accident"

    def overlaps(self, start: float, end: float, tolerance: float = 0.0) -> bool:
        """Does ``[start, end]`` intersect this event window?"""
        return (start - tolerance) <= self.end_seconds and (start + end) >= self.start_seconds

    def to_dict(self) -> Dict[str, Any]:
        return {
            "kind": self.kind,
            "start_seconds": round(float(self.start_seconds), 3),
            "end_seconds": round(float(self.end_seconds), 3),
            "subtype": self.subtype,
            "note": self.note,
            "verified_by": self.verified_by,
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any], where: str) -> "EventLabel":
        missing = [k for k in ("kind", "start_seconds", "end_seconds") if k not in data]
        if missing:
            raise ManifestError(f"{where}: event missing {missing}")
        if data["kind"] not in ("accident", "hard_negative", "normal"):
            raise ManifestError(f"{where}: unknown event kind {data['kind']!r}")
        start, end = float(data["start_seconds"]), float(data["end_seconds"])
        if end < start:
            raise ManifestError(f"{where}: event ends ({end}) before it starts ({start})")
        return cls(
            kind=str(data["kind"]),
            start_seconds=start,
            end_seconds=end,
            subtype=str(data.get("subtype", "")),
            note=str(data.get("note", "")),
            verified_by=str(data.get("verified_by", "")),
        )


@dataclass
class ClipLabel:
    """One labelled clip.

    ``source_id`` is the **leakage group**: every clip from the same recording,
    camera, location or time block shares one.  The splitter never puts two
    clips of the same group on different sides of a split, which is what stops
    near-duplicate frames from leaking.
    """

    clip: str
    label: str                      # "accident" | "normal"  (clip-level truth)
    source_id: str
    camera_id: str = ""
    location_id: str = ""
    recorded_at: str = ""
    quality: str = "SYNTHETIC"
    note: str = ""
    events: List[EventLabel] = field(default_factory=list)

    @property
    def is_real_footage(self) -> bool:
        return self.quality != "SYNTHETIC"

    @property
    def is_ground_truth(self) -> bool:
        """Only independently reviewed labels may support a quality claim."""
        return self.quality == "VERIFIED"

    def positive_windows(self, tolerance: float = 0.0) -> List[Tuple[float, float]]:
        return [
            (e.start_seconds, e.end_seconds)
            for e in self.events
            if e.is_positive
        ]

    def to_dict(self) -> Dict[str, Any]:
        return {
            "clip": self.clip,
            "label": self.label,
            "source_id": self.source_id,
            "camera_id": self.camera_id,
            "location_id": self.location_id,
            "recorded_at": self.recorded_at,
            "quality": self.quality,
            "note": self.note,
            "events": [e.to_dict() for e in self.events],
        }

    @classmethod
    def from_dict(cls, data: Dict[str, Any], root: Path, index: int) -> "ClipLabel":
        where = f"clips[{index}]"
        for key in ("clip", "label", "source_id", "quality"):
            if key not in data:
                raise ManifestError(f"{where}: missing {key!r}")
        if data["label"] not in ("accident", "normal"):
            raise ManifestError(f"{where}: label must be 'accident' or 'normal'")
        if data["quality"] not in GRADES:
            raise ManifestError(
                f"{where}: quality {data['quality']!r} not in {list(GRADES)}"
            )
        clip_path = Path(str(data["clip"]))
        resolved = clip_path if clip_path.is_absolute() else root / clip_path
        if not resolved.is_file():
            raise ManifestError(f"{where}: clip file not found: {resolved}")
        events = [
            EventLabel.from_dict(e, f"{where}.events[{i}]")
            for i, e in enumerate(data.get("events") or [])
        ]
        # a clip labelled "accident" must actually declare one
        if data["label"] == "accident" and not any(e.is_positive for e in events):
            raise ManifestError(
                f"{where}: label='accident' but no event with kind='accident'"
            )
        return cls(
            clip=str(resolved),
            label=str(data["label"]),
            source_id=str(data["source_id"]),
            camera_id=str(data.get("camera_id", "")),
            location_id=str(data.get("location_id", "")),
            recorded_at=str(data.get("recorded_at", "")),
            quality=str(data["quality"]),
            note=str(data.get("note", "")),
            events=events,
        )


@dataclass
class EvalManifest:
    """A whole evaluation set."""

    name: str = "unnamed"
    version: str = "0"
    description: str = ""
    clips: List[ClipLabel] = field(default_factory=list)
    root: Path = field(default_factory=Path)
    path: Optional[Path] = None

    # ------------------------------------------------------------------ #
    def groups(self) -> Dict[str, List[ClipLabel]]:
        """Leakage groups keyed by ``source_id``."""
        out: Dict[str, List[ClipLabel]] = {}
        for clip in self.clips:
            out.setdefault(clip.source_id, []).append(clip)
        return out

    def usable_for_quality_claims(self) -> bool:
        """Is this set allowed to support an accuracy statement?

        Only if it is entirely real footage and every label is verified.
        """
        return bool(self.clips) and all(c.is_ground_truth and c.is_real_footage for c in self.clips)

    def quality_blockers(self) -> List[str]:
        """Why this set may not support a quality claim - stated, not hidden."""
        blockers: List[str] = []
        if not self.clips:
            blockers.append("the set is empty")
        synthetic = [c.clip for c in self.clips if not c.is_real_footage]
        if synthetic:
            blockers.append(
                f"{len(synthetic)} clip(s) are synthetic and cannot measure detector quality"
            )
        unverified = [c.clip for c in self.clips if c.quality != "VERIFIED"]
        if unverified:
            grades = sorted({c.quality for c in self.clips if c.quality != "VERIFIED"})
            blockers.append(
                f"{len(unverified)} clip(s) are not independently verified (grades: {grades})"
            )
        real = [c for c in self.clips if c.is_real_footage]
        if len(real) < 20:
            blockers.append(
                f"only {len(real)} real clip(s); at least ~20 clips from >=5 distinct "
                "cameras/locations are needed before any rate is meaningful"
            )
        sources = len({c.source_id for c in self.clips})
        if sources < 5:
            blockers.append(f"only {sources} independent source group(s); leakage-safe splits need >=5")
        return blockers

    def describe(self) -> Dict[str, Any]:
        real = [c for c in self.clips if c.is_real_footage]
        verified = [c for c in self.clips if c.is_ground_truth]
        positives = [c for c in self.clips if c.label == "accident"]
        events = sum(len(c.positive_windows()) for c in self.clips)
        return {
            "name": self.name,
            "version": self.version,
            "clips": len(self.clips),
            "real_clips": len(real),
            "synthetic_clips": len(self.clips) - len(real),
            "verified_clips": len(verified),
            "positive_clips": len(positives),
            "negative_clips": len(self.clips) - len(positives),
            "positive_events": events,
            "source_groups": len(self.groups()),
            "cameras": sorted({c.camera_id for c in self.clips if c.camera_id}),
            "usable_for_quality_claims": self.usable_for_quality_claims(),
            "quality_blockers": self.quality_blockers(),
        }

    def to_dict(self) -> Dict[str, Any]:
        return {
            "name": self.name,
            "version": self.version,
            "description": self.description,
            "clips": [c.to_dict() for c in self.clips],
        }


def load_manifest(path: str | Path) -> EvalManifest:
    """Read and validate a manifest.  Raises :class:`ManifestError` on any problem."""
    p = Path(path)
    if not p.is_file():
        raise ManifestError(f"manifest not found: {p}")
    try:
        raw = json.loads(p.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ManifestError(f"{p}: invalid JSON ({exc})") from exc
    if not isinstance(raw, dict) or "clips" not in raw:
        raise ManifestError(f"{p}: expected an object with a 'clips' array")

    root = p.parent
    clips = [ClipLabel.from_dict(c, root, i) for i, c in enumerate(raw.get("clips") or [])]
    manifest = EvalManifest(
        name=str(raw.get("name", p.stem)),
        version=str(raw.get("version", "0")),
        description=str(raw.get("description", "")),
        clips=clips,
        root=root,
        path=p,
    )
    seen: Dict[str, str] = {}
    for clip in clips:
        if clip.clip in seen:
            raise ManifestError(f"{p}: clip listed twice: {clip.clip}")
        seen[clip.clip] = clip.source_id
    return manifest